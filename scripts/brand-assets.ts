/**
 * Brand pipeline (10 §2 step 3, 06 §5).
 *
 *   ASSETS/  (originals — never modified, source of truth)
 *     → public/brand/<slug>.svg|png       ASCII slugs; SVGs through lossless SVGO
 *     → src/components/brand/generated/   SVGR components (inline SVG, CSP-safe)
 *
 * Run: npm run brand:assets   (idempotent; output is committed)
 */
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { transform } from '@svgr/core';
import { optimize } from 'svgo';
import { svgoConfig } from '../svgo.config.mjs';
import { componentName, ICONS, PALETTE, svgEntries } from './brand-map';

const ROOT = join(import.meta.dirname, '..');
const ASSETS = join(ROOT, 'ASSETS');
const OUT = join(ROOT, 'public/brand');
const COMPONENTS = join(ROOT, 'src/components/brand/generated');

const HEADER = '// AUTO-GENERATED by scripts/brand-assets.ts from ASSETS/ — do not edit.\n';

/** Fails if the asset isn't the colour the map says (guards against a wrong mapping). */
function assertColour(svg: string, expected: string, file: string): void {
  const fills = new Set(
    [...svg.matchAll(/fill(?:=")?:?\s*(#[0-9a-f]{6})/gi)].map((m) => m[1]!.toLowerCase()),
  );
  if (fills.size !== 1 || !fills.has(expected)) {
    throw new Error(`${file}: expected only ${expected}, found ${[...fills].join(', ') || 'none'}`);
  }
}

/** Fails on anything that must never be inlined into our pages. */
function assertSafe(svg: string, file: string): void {
  const forbidden =
    /<script|<foreignObject|\son[a-z]+\s*=|javascript:|xlink:href\s*=\s*"(?!#)|href\s*=\s*"(?!#)/i;
  if (forbidden.test(svg)) throw new Error(`${file}: contains scripts, handlers or external refs`);
  if (/<style/i.test(svg))
    throw new Error(`${file}: <style> survived SVGO (would be blocked by CSP)`);
}

async function main(): Promise<void> {
  await rm(OUT, { recursive: true, force: true });
  await rm(COMPONENTS, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
  await mkdir(COMPONENTS, { recursive: true });

  const manifest: Record<string, { source: string; sha256: string }> = {};
  const exports: string[] = [];

  for (const entry of svgEntries()) {
    const sourcePath = join(ASSETS, entry.source);
    const original = await readFile(sourcePath, 'utf8');
    assertColour(original, PALETTE[entry.colour], entry.source);

    const { data: processed } = optimize(original, { path: sourcePath, ...svgoConfig(entry.slug) });
    assertSafe(processed, entry.source);
    assertColour(processed, PALETTE[entry.colour], `${entry.slug}.svg (processed)`);
    await writeFile(join(OUT, `${entry.slug}.svg`), processed);
    await copyFile(join(ASSETS, entry.pngSource), join(OUT, `${entry.slug}.png`));
    manifest[`${entry.slug}.svg`] = {
      source: entry.source,
      sha256: createHash('sha256').update(original).digest('hex'),
    };

    if (entry.component) {
      const name = componentName(entry.slug);
      // The root id/data-name are unreferenced Illustrator leftovers; dropping them keeps ids
      // unique when a component renders twice on one page (pixel-diffed like everything else).
      const componentSvg = processed.replace(/^<svg id="[^"]*" data-name="[^"]*"/, '<svg');
      const code = await transform(
        componentSvg,
        {
          plugins: ['@svgr/plugin-jsx'],
          typescript: true,
          jsxRuntime: 'automatic',
          svgo: false, // already optimised losslessly above
          dimensions: false, // size comes from CSS classes
          titleProp: true,
          expandProps: 'end',
          svgProps: { focusable: 'false' },
          exportType: 'default',
        },
        { componentName: name },
      );
      await writeFile(join(COMPONENTS, `${name}.tsx`), HEADER + code);
      exports.push(`export { default as ${name} } from './${name}';`);
    }
  }

  for (const icon of ICONS) {
    await copyFile(join(ASSETS, icon.source), join(OUT, `${icon.slug}.png`));
  }

  await writeFile(join(COMPONENTS, 'index.ts'), HEADER + exports.sort().join('\n') + '\n');
  await writeFile(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log(
    `brand: ${Object.keys(manifest).length} SVGs, ${exports.length} components, ${ICONS.length} icons`,
  );
}

await main();
