/**
 * Web fonts (06 §3): self-hosted woff2 subsets — Latin + Latin-1 + punctuation — of the licensed
 * originals in ASSETS/FONTS, loaded with next/font/local (src/app/fonts.ts). Same origin → CSP
 * `font-src 'self'`.
 *
 * Run: npm run brand:fonts
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'src/app/fonts');

/** Unicode ranges kept in every subset. */
export const UNICODE_RANGES: [number, number][] = [
  [0x0020, 0x007e], // Basic Latin
  [0x00a0, 0x00ff], // Latin-1 Supplement (ã õ ç á é í ó ú â ê ô à ü º ª « » …)
  [0x0131, 0x0131], // ı
  [0x0152, 0x0153], // Œ œ
  [0x02c6, 0x02c6], // ˆ
  [0x02da, 0x02da], // ˚
  [0x02dc, 0x02dc], // ˜
  [0x2013, 0x2014], // – —
  [0x2018, 0x201e], // ‘ ’ ‚ “ ” „
  [0x2022, 0x2022], // •
  [0x2026, 0x2026], // …
  [0x2030, 0x2030], // ‰
  [0x2039, 0x203a], // ‹ ›
  [0x20ac, 0x20ac], // €
  [0x2122, 0x2122], // ™
  [0x2212, 0x2212], // −
];

export const SUBSET_TEXT = UNICODE_RANGES.flatMap(([a, b]) =>
  Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i)),
).join('');

const FONTS = [
  { src: 'Poppins/Poppins-Regular.ttf', out: 'poppins-400.woff2' },
  { src: 'Poppins/Poppins-Medium.ttf', out: 'poppins-500.woff2' },
  { src: 'Poppins/Poppins-SemiBold.ttf', out: 'poppins-600.woff2' },
  { src: 'Poppins/Poppins-Bold.ttf', out: 'poppins-700.woff2' },
  { src: 'Escargoth/OpenType-TT/Escargoth.ttf', out: 'escargoth.woff2' },
  { src: 'Black Rockie/BlackRockie.ttf', out: 'black-rockie.woff2' },
];

async function main(): Promise<void> {
  await mkdir(OUT, { recursive: true });
  for (const font of FONTS) {
    const original = await readFile(join(ROOT, 'ASSETS/FONTS', font.src));
    const woff2 = await subsetFont(original, SUBSET_TEXT, { targetFormat: 'woff2' });
    await writeFile(join(OUT, font.out), woff2);
    console.log(
      `fonts: ${font.out.padEnd(20)} ${(original.length / 1024).toFixed(0).padStart(4)} KB → ${(woff2.length / 1024).toFixed(1)} KB`,
    );
  }
  // SIL OFL 1.1 requires the licence to accompany redistributed font software.
  await copyFile(join(ROOT, 'ASSETS/FONTS/Poppins/OFL.txt'), join(OUT, 'Poppins-OFL.txt'));
  await writeFile(
    join(OUT, 'README.md'),
    '# Fonts\n\nGenerated by `npm run brand:fonts` from `ASSETS/FONTS` (subset: Latin, Latin-1, punctuation).\n\n' +
      '- Poppins — SIL Open Font License 1.1 (`Poppins-OFL.txt`).\n' +
      '- Escargoth (Drizy Studio) and Black Rockie (UICreative) — commercial licences held by the site owner; ' +
      'do not redistribute outside this website.\n',
  );
}

if (process.argv[1]?.endsWith('fonts.ts')) await main();
