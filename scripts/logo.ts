/**
 * Logo "Wiski" (06 §8): outlines generated from the licensed Black Rockie font's own glyphs,
 * shaped with the font's kerning (opentype.js) — never hand-drawn. One path, filled with a
 * palette colour, tight viewBox in font units (1 unit = 1/unitsPerEm em).
 *
 *   public/brand/logo-wiski-{ink,lilac,lavender}.svg  +  SVGR components
 *
 * Run: npm run brand:logo
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { transform } from '@svgr/core';
import opentype from 'opentype.js';
import { PALETTE, type BrandColour, componentName } from './brand-map';

export const LOGO_TEXT = 'Wiski';
export const LOGO_FONT = 'ASSETS/FONTS/Black Rockie/BlackRockie.ttf';
const COLOURS: BrandColour[] = ['ink', 'lilac', 'lavender'];

const ROOT = join(import.meta.dirname, '..');
const HEADER = '// AUTO-GENERATED by scripts/logo.ts from ASSETS/FONTS — do not edit.\n';

export async function buildLogoGeometry(root = ROOT) {
  const buf = await readFile(join(root, LOGO_FONT));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  // Baseline at y = 0, size = unitsPerEm → coordinates are exact font units (no rounding).
  const path = font.getPath(LOGO_TEXT, 0, 0, font.unitsPerEm, { kerning: true, features: {} });
  const box = path.getBoundingBox();
  const viewBox = [box.x1, box.y1, box.x2 - box.x1, box.y2 - box.y1].map((n) => +n.toFixed(3));
  return {
    // opentype.js 2 flips Y by default in toPathData; getPath already returns SVG (y-down) coords.
    d: path.toPathData({ decimalPlaces: 3, flipY: false, optimize: false }),
    viewBox,
    unitsPerEm: font.unitsPerEm,
    box: { x1: box.x1, y1: box.y1, x2: box.x2, y2: box.y2 },
  };
}

async function main(): Promise<void> {
  const geo = await buildLogoGeometry();
  const exports: string[] = [];
  for (const colour of COLOURS) {
    const slug = `logo-wiski-${colour}`;
    const svg =
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${geo.viewBox.join(' ')}" role="img" aria-label="${LOGO_TEXT}">\n` +
      `  <path d="${geo.d}" fill="${PALETTE[colour]}"/>\n` +
      `</svg>\n`;
    await writeFile(join(ROOT, 'public/brand', `${slug}.svg`), svg);

    const name = componentName(slug);
    const code = await transform(
      svg.replace(' role="img" aria-label="Wiski"', ''),
      {
        plugins: ['@svgr/plugin-jsx'],
        typescript: true,
        jsxRuntime: 'automatic',
        svgo: false,
        dimensions: false,
        titleProp: true,
        expandProps: 'end',
        svgProps: { focusable: 'false' },
        exportType: 'default',
      },
      { componentName: name },
    );
    await writeFile(join(ROOT, 'src/components/brand/generated', `${name}.tsx`), HEADER + code);
    exports.push(`export { default as ${name} } from './${name}';`);
  }

  // Append logo exports to the generated index (written by brand-assets.ts).
  const indexPath = join(ROOT, 'src/components/brand/generated/index.ts');
  const index = (await readFile(indexPath, 'utf8'))
    .split('\n')
    .filter((l) => !l.includes('LogoWiski'));
  await writeFile(indexPath, [...index.filter(Boolean), ...exports].join('\n') + '\n');
  await writeFile(
    join(ROOT, 'public/brand/logo-wiski.json'),
    JSON.stringify(
      { text: LOGO_TEXT, viewBox: geo.viewBox, unitsPerEm: geo.unitsPerEm, box: geo.box },
      null,
      2,
    ) + '\n',
  );
  console.log(
    `logo: viewBox ${geo.viewBox.join(' ')} (aspect ${(geo.viewBox[2]! / geo.viewBox[3]!).toFixed(3)})`,
  );
}

if (process.argv[1]?.endsWith('logo.ts')) await main();
