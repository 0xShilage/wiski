#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Refresh Cloudflare's IP ranges (weekly timer: wiskiflix-cloudflare-ips.timer). They feed two
# things that must agree: nginx's real-IP trust list (/etc/wiskiflix/nginx/cloudflare-real-ip.conf,
# mounted over the committed baseline docker/nginx/snippets/cloudflare-real-ip.conf) and the
# firewall (firewall.sh). A suspicious download (too few ranges, not CIDR) is rejected and the
# previous list stays.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
ETC=/etc/wiskiflix
cd /opt/wiskiflix
umask 022
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsS --proto '=https' --max-time 20 https://www.cloudflare.com/ips-v4 -o "$tmp/v4"
curl -fsS --proto '=https' --max-time 20 https://www.cloudflare.com/ips-v6 -o "$tmp/v6"
grep -Evq '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' "$tmp/v4" && { echo "unexpected v4 list"; exit 1; }
grep -Evq '^[0-9a-f:]+/[0-9]{1,3}$' "$tmp/v6" && { echo "unexpected v6 list"; exit 1; }
[ "$(wc -l < "$tmp/v4")" -ge 10 ] && [ "$(wc -l < "$tmp/v6")" -ge 5 ] || { echo "list too short"; exit 1; }

{
  echo "# Generated by scripts/ops/cloudflare-ips.sh on $(date -u +%F) from https://www.cloudflare.com/ips/"
  sed 's/^/set_real_ip_from /; s/$/;/' "$tmp/v4" "$tmp/v6"
  echo 'real_ip_header CF-Connecting-IP;'
  echo 'real_ip_recursive off;'
} > "$tmp/real-ip.conf"

changed=0
mkdir -p "$ETC/nginx"
for pair in "v4:$ETC/cloudflare-ips-v4.txt" "v6:$ETC/cloudflare-ips-v6.txt" "real-ip.conf:$ETC/nginx/cloudflare-real-ip.conf"; do
  src="$tmp/${pair%%:*}"; dst="${pair#*:}"
  if ! cmp -s <(grep -v '^#' "$src") <(grep -v '^#' "$dst" 2>/dev/null); then
    cp "$src" "$dst"; changed=1
  fi
done

if [ "$changed" = 1 ]; then
  echo "Cloudflare ranges changed: reloading firewall and nginx"
  scripts/ops/firewall.sh
  if docker compose -f docker/compose.prod.yml ps --status running --services 2>/dev/null | grep -qx nginx; then
    docker compose -f docker/compose.prod.yml exec -T nginx nginx -s reload
  fi
else
  echo "Cloudflare ranges unchanged"
fi
