/**
 * Platform glyphs for the Links page (2026-11-01) from Simple Icons (CC0-1.0, simpleicons.org).
 * The logos stay their owners' trademarks; they are used only on buttons that link to the
 * streamer's own profile on that platform (each brand's guidelines allow that).
 *
 * Simple Icons is not a dependency (≈ 26 MB for a dozen paths). To regenerate:
 *
 *   npm pack simple-icons@16.36.0 && tar xzf simple-icons-16.36.0.tgz
 *   npx tsx scripts/platform-icons.ts ./package && npx prettier --write src/components/links
 *
 * Amazon is no longer in Simple Icons (Amazon asked for its removal), and Cinefy has no entry:
 * both get generic drawn icons in PlatformIcon.tsx instead.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SLUGS: Record<string, string> = {
  Twitch: 'twitch',
  YouTube: 'youtube',
  Kick: 'kick',
  TikTok: 'tiktok',
  Instagram: 'instagram',
  X: 'x',
  Discord: 'discord',
  Threads: 'threads',
  Bluesky: 'bluesky',
  Facebook: 'facebook',
  Spotify: 'spotify',
  WhatsApp: 'whatsapp',
  Letterboxd: 'letterboxd',
  Steam: 'steam',
};

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: tsx scripts/platform-icons.ts <unpacked simple-icons package dir>');
  process.exit(1);
}
const version = (JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')) as { version: string })
  .version;

const out: Record<string, string> = {};
for (const [name, slug] of Object.entries(SLUGS)) {
  const svg = readFileSync(join(pkg, 'icons', `${slug}.svg`), 'utf8');
  if (!svg.includes('viewBox="0 0 24 24"')) throw new Error(`${slug}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)].map((m) => m[1]!);
  if (paths.length !== 1 || /style|<script|on[a-z]+=/i.test(svg))
    throw new Error(`${slug}: expected exactly one plain path`);
  if (!/^[MZLHVCSQTA0-9.,\s-]+$/i.test(paths[0]!))
    throw new Error(`${slug}: path data has unexpected characters`);
  out[name] = paths[0]!;
}

const body = `/**
 * GENERATED by scripts/platform-icons.ts from Simple Icons ${version} (CC0-1.0). Do not edit.
 * Single-path 24 × 24 glyphs, drawn with fill="currentColor". Trademarks of their owners.
 */
export const PLATFORM_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(
  join(import.meta.dirname, '../src/components/links/platform-icons.generated.ts'),
  body,
);
console.log(`platform-icons: ${Object.keys(out).length} glyphs from simple-icons ${version}`);
