// Creates .env.local for LOCAL DEVELOPMENT with fresh random secrets (generated on this machine;
// nothing is sent anywhere). Database/Redis URLs match docker/compose.dev.yml.
//   node scripts/setup-dev-env.mjs          (refuses to overwrite an existing .env.local)
//   node scripts/setup-dev-env.mjs --force  (replace it)
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const file = '.env.local';
if (existsSync(file) && !process.argv.includes('--force')) {
  console.error(`${file} already exists — left untouched (use --force to replace it).`);
  process.exit(1);
}
const secret = () => randomBytes(32).toString('base64url');

writeFileSync(
  file,
  `# Local development only — generated by scripts/setup-dev-env.mjs. Never commit (git-ignored).
APP_ORIGIN=http://localhost:3000

# docker/compose.dev.yml (dev-only passwords, see docker/dev/init-roles.sh)
DATABASE_URL=postgresql://wf_app:dev-app@localhost:5432/wiskiflix
MIGRATE_DATABASE_URL=postgresql://wf_migrator:dev-migrator@localhost:5432/wiskiflix
SHADOW_DATABASE_URL=postgresql://wf_migrator:dev-migrator@localhost:5432/wiskiflix_shadow
REDIS_URL=redis://localhost:6379

CSRF_SECRET=${secret()}
COOKIE_SEAL_KEY=${secret()}
IP_HASH_SECRET=${secret()}
TOTP_ENCRYPTION_KEY=${secret()}
CLIENT_IP_HEADER=none

# Google sign-in (Q27): paste the client id, and type the secret yourself.
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=

# Mercado Pago TEST credentials only (Phase 2).
MP_COLLECTOR_ID=
MP_APPLICATION_ID=
MP_ACCESS_TOKEN=
MP_WEBHOOK_SECRET=

# Empty = <project>/.media
MEDIA_DIR=
LOG_LEVEL=info
`,
  { mode: 0o600 },
);
console.log(`${file} created with new random secrets.`);
